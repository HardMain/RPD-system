async def _get_or_create_discipline_by_name(db, name: str) -> Discipline:
    res = await db.execute(select(Discipline).where(Discipline.name == name))
    d = res.scalars().first()
    if d:
        return d
    d = Discipline(name=name)
    db.add(d)
    await db.flush()
    return d
