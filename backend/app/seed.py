def _template_needs_upgrade(section_key: str, template: str) -> bool:
    template = template or ""
    if REFERENCE_AWARE_MARKER not in template:
        return True
    if PRIORITY_LADDER_MARKER not in template:
        return True
    if section_key == "content" and SEMESTERS_PLAN_MARKER not in template:
        return True
    marker = _CATALOG_MARKERS.get(section_key)
    if marker and marker not in template:
        return True
    style_marker = _STYLE_MARKERS.get(section_key)
    if style_marker and style_marker not in template:
        return True
    return False


def _prompt_needs_upgrade(row: LlmPrompt) -> bool:
    return _template_needs_upgrade(row.section_key, row.user_prompt_template or "")


async def upgrade_llm_prompts_to_reference_aware():
    async with async_session() as db:
        defaults_by_key = {spec["section_key"]: spec for spec in DEFAULT_LLM_PROMPTS}
        result = await db.execute(select(LlmPrompt))
        rows = result.scalars().all()
        upgraded = 0
        for row in rows:
            spec = defaults_by_key.get(row.section_key)
            if not spec:
                continue
            factory_user = spec["user_prompt_template"]
            current_user = row.user_prompt_template or ""
            saved_default = row.default_user_prompt_template or ""
            admin_customized = bool(saved_default) and current_user != saved_default
            changed = False
            if _template_needs_upgrade(row.section_key, saved_default or current_user):
                if not admin_customized:
                    row.user_prompt_template = factory_user
                row.default_user_prompt_template = factory_user
                row.description = spec.get("description") or row.description
                row.is_structural = spec.get("is_structural", row.is_structural)
                changed = True
            elif not saved_default:
                row.default_user_prompt_template = current_user
                changed = True
            spec_label = spec.get("section_label")
            if spec_label and row.section_label != spec_label:
                row.section_label = spec_label
                changed = True
            spec_order = spec.get("order_index")
            if spec_order is not None and row.order_index != spec_order:
                row.order_index = spec_order
                changed = True
            if changed:
                upgraded += 1
        if upgraded:
            await db.commit()
            print(f"✅ LLM prompts upgraded ({upgraded} updated)")


